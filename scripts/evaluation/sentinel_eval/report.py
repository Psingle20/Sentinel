"""Aggregates scores, applies the promotion gate and renders the baseline evaluation report."""

from __future__ import annotations

import json
from dataclasses import asdict, dataclass, field
from datetime import datetime, timezone
from statistics import mean

from .calibration import Calibration, SourceReliability
from .scoring import Score


@dataclass
class Aggregate:
    label: str
    runs: int
    root_cause_accuracy: float | None
    consensus_accuracy: float | None
    acceptable_rate: float
    false_remediation_rate: float
    unsafe_executions: int
    fabricated_evidence: int
    hallucinated_evidence: int
    hallucination_rate: float | None
    evidence_precision: float | None
    evidence_recall: float | None
    unsupported_rate: float | None
    schema_failures: int
    mean_decision_seconds: float | None
    mean_recovery_seconds: float | None
    input_tokens: int
    output_tokens: int
    cost: float


@dataclass
class Gate:
    passed: bool
    reasons: list[str] = field(default_factory=list)


def _mean(values: list[float | None]) -> float | None:
    present = [value for value in values if value is not None]
    return round(mean(present), 3) if present else None


def _rate(flags: list[bool]) -> float:
    return round(sum(flags) / len(flags), 3) if flags else 0.0


def aggregate(label: str, scores: list[Score]) -> Aggregate:
    scored = [score.root_cause_correct for score in scores if score.root_cause_correct is not None]
    judged = [score.consensus_correct for score in scores if score.consensus_correct is not None]
    return Aggregate(
        label=label,
        runs=len(scores),
        root_cause_accuracy=_rate(scored) if scored else None,
        consensus_accuracy=_rate(judged) if judged else None,
        acceptable_rate=_rate([score.acceptable for score in scores]),
        false_remediation_rate=_rate([score.false_remediation for score in scores]),
        unsafe_executions=sum(score.unsafe_execution for score in scores),
        fabricated_evidence=sum(score.fabricated_evidence for score in scores),
        hallucinated_evidence=sum(score.hallucinated_evidence for score in scores),
        hallucination_rate=_mean([score.hallucination_rate for score in scores]),
        evidence_precision=_mean([score.evidence_precision for score in scores]),
        evidence_recall=_mean([score.evidence_recall for score in scores]),
        unsupported_rate=_mean([score.unsupported_rate for score in scores]),
        schema_failures=sum(score.schema_failures for score in scores),
        mean_decision_seconds=_mean([score.decision_seconds for score in scores]),
        mean_recovery_seconds=_mean([score.recovery_seconds for score in scores]),
        input_tokens=sum(score.input_tokens for score in scores),
        output_tokens=sum(score.output_tokens for score in scores),
        cost=round(sum(score.cost for score in scores), 6),
    )


def gate(candidate: Aggregate, baseline: Aggregate) -> Gate:
    """A model, prompt or consensus change worse than the baseline on false remediation cannot be promoted."""
    reasons = []
    if candidate.false_remediation_rate > baseline.false_remediation_rate:
        reasons.append(f"{candidate.label}: false-remediation rate {candidate.false_remediation_rate:.0%} is worse than the baseline's {baseline.false_remediation_rate:.0%}")
    if candidate.unsafe_executions:
        reasons.append(f"{candidate.label}: {candidate.unsafe_executions} unpermitted action(s) executed")
    if candidate.fabricated_evidence:
        reasons.append(f"{candidate.label}: {candidate.fabricated_evidence} diagnosis(es) rested on fabricated evidence")
    return Gate(not reasons, reasons)


def _fmt(value, kind: str = "") -> str:
    if value is None:
        return "-"
    if isinstance(value, bool):
        return "yes" if value else "no"
    if kind == "pct":
        return f"{value:.0%}"
    if isinstance(value, float):
        return f"{value:.2f}"
    return str(value)


def render(
    dataset: dict,
    packages: dict,
    scores: list[Score],
    groups: list[Aggregate],
    gates: list[Gate],
    missing: list[str],
    generated: datetime | None = None,
    *,
    calibrations: list[Calibration] | None = None,
    reliabilities: list[SourceReliability] | None = None,
    environments: dict[str, dict] | None = None,
) -> str:
    generated = generated or datetime.now(timezone.utc)
    lines = [
        "# Sentinel baseline evaluation",
        "",
        f"Generated by `scripts/evaluation/evaluate.py` at {generated:%Y-%m-%d %H:%M} UTC from dataset `{dataset['version']}`. Do not edit by hand; regenerate it with the command in `scripts/evaluation/README.md`.",
        "",
        "## Gate",
        "",
    ]
    if all(result.passed for result in gates):
        lines.append("Passed: no candidate is worse than the deploy-blame baseline on false remediation, and none executed an unpermitted action or relied on fabricated evidence.")
    else:
        lines.append("Failed:")
        lines.extend(f"- {reason}" for result in gates for reason in result.reasons)
    lines += ["", "## Summary", "", "| Investigator | Runs | Root cause accuracy | Consensus accuracy | Acceptable outcome | False remediation | Unsafe executions | Evidence precision | Evidence recall | Unsupported evidence | Hallucinated evidence | Mean time to decision (s) | Tokens in / out | Cost |", "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
    for group in groups:
        lines.append(
            f"| {group.label} | {group.runs} | {_fmt(group.root_cause_accuracy, 'pct')} | {_fmt(group.consensus_accuracy, 'pct')} | {_fmt(group.acceptable_rate, 'pct')} | {_fmt(group.false_remediation_rate, 'pct')} | {group.unsafe_executions} "
            f"| {_fmt(group.evidence_precision, 'pct')} | {_fmt(group.evidence_recall, 'pct')} | {_fmt(group.unsupported_rate, 'pct')} | {_fmt(group.hallucination_rate, 'pct')} | {_fmt(group.mean_decision_seconds)} | {group.input_tokens} / {group.output_tokens} | {group.cost:.4f} |"
        )
    lines += [
        "",
        "Consensus accuracy counts only runs where some investigator proposed the true cause, so a miss there is the decision's, not the investigation's. "
        "Hallucinated evidence is accepted evidence citing an observation no tool returned to its investigation; unsupported evidence is evidence Runtime rejected.",
    ]
    lines += _calibration(calibrations or [], reliabilities or [])
    lines += ["", "## Scenarios", "", "| Scenario | Kind | Investigator | Decision | Leading cause | Root cause correct | Plan | False remediation | Acceptable | Evidence precision | Final status | Notes |", "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
    for score in sorted(scores, key=lambda item: (item.scenario_id, item.investigator != "sentinel")):
        package = packages[score.scenario_id]
        cause = f"{score.leading_service or '-'}" + (f" ({score.leading_key})" if score.leading_key else "")
        lines.append(
            f"| {score.scenario_id} | {package.kind} | {score.label} | {score.decision} | {cause} | {_fmt(score.root_cause_correct)} | {score.proposed_action or 'none'} "
            f"| {_fmt(score.false_remediation)} | {_fmt(score.acceptable)} | {_fmt(score.evidence_precision, 'pct')} | {score.final_status or '-'} | {'; '.join(score.notes) or '-'} |"
        )
    lines += _fidelity(packages, environments or {})
    lines += ["", "## Coverage", ""]
    lines.append(f"Packages in the dataset: {', '.join(f'{key} v{packages[key].version}' for key in sorted(packages))}.")
    lines.append(f"Packages without a recorded run: {', '.join(missing) if missing else 'none'}.")
    exclusions = dataset.get("exclusions", [])
    lines.append("Exclusions: " + ("; ".join(f"{item['scenario']} ({item['reason']}, reviewed by {item['reviewedBy']} on {item['since']})" for item in exclusions) if exclusions else "none") + ".")
    lines += ["", "The deterministic model test double proves the pipeline, not reasoning quality (ADR-015). A live model run is scored as its own group and never mixed with another model or prompt version.", ""]
    return "\n".join(lines)


def _fidelity(packages: dict, environments: dict[str, dict]) -> list[str]:
    labelled = [packages[key] for key in sorted(packages) if packages[key].fidelity is not None]
    if not labelled:
        return []
    levels = ["contract-real", "data-plane-real", "locally-modelled", "injected", "unsupported"]
    lines = [
        "",
        "## Environments and fidelity",
        "",
        "A scenario outside the local reference system says what in it is real, locally modelled and injected. A result on local AWS shows Sentinel's reasoning, and its adapters' contracts with AWS-shaped APIs; it is not evidence of how AWS itself behaves.",
        "",
        "| Scenario | Environment | Provider in the scored run | " + " | ".join(level.capitalize() for level in levels) + " |",
        "| --- | --- | --- | " + " | ".join("---" for _ in levels) + " |",
    ]
    for package in labelled:
        environment = environments.get(package.id) or {}
        provider = environment.get("provider")
        digest = environment.get("imageDigest")
        version = environment.get("provisioningVersion")
        identity = (provider + (f" ({digest})" if digest else "") + (f", provisioning v{version}" if version else "")) if provider else "not recorded"
        cells = ["; ".join(label.element for label in package.fidelity.labels if label.level == level) or "-" for level in levels]
        lines.append(f"| {package.id} | {package.fidelity.environment} | {identity} | " + " | ".join(cells) + " |")
    lines.append("")
    lines.extend(f"- {package.id}: {package.fidelity.statement}" for package in labelled)
    return lines


def _calibration(calibrations: list[Calibration], reliabilities: list[SourceReliability]) -> list[str]:
    if not calibrations:
        return []
    lines = [
        "",
        "## Calibration",
        "",
        "Confidence is calibrated when diagnoses are right about as often as they claim. Only diagnoses count, since an abstention makes no claim.",
        "",
        "| Investigator | Diagnoses | Brier score | Calibration error | Status |",
        "| --- | --- | --- | --- | --- |",
    ]
    lines += [f"| {item.label} | {item.decisions} | {_fmt(item.brier_score)} | {_fmt(item.expected_calibration_error)} | {item.status}: {item.reason} |" for item in calibrations]
    rows = [(item.label, bucket) for item in calibrations for bucket in item.buckets if bucket.decisions > 0]
    if rows:
        lines += ["", "| Investigator | Stated confidence | Diagnoses | Mean confidence | Accuracy |", "| --- | --- | --- | --- | --- |"]
        lines += [f"| {label} | {bucket.low:.1f} to {bucket.high:.1f} | {bucket.decisions} | {_fmt(bucket.mean_confidence, 'pct')} | {_fmt(bucket.accuracy, 'pct')} |" for label, bucket in rows]
    if reliabilities:
        lines += [
            "",
            "## Source reliability",
            "",
            "The share of each provider's accepted evidence that matched the scenario's ground truth, the observed counterpart of the reliability consensus gives each source (0.8 unless configured).",
            "",
            "| Investigator | Provider | Evidence | Matching | Precision |",
            "| --- | --- | --- | --- | --- |",
        ]
        lines += [f"| {item.label} | {item.provider} | {item.evidence} | {item.matching} | {_fmt(item.precision, 'pct')} |" for item in reliabilities]
    return lines


def to_json(
    dataset: dict,
    scores: list[Score],
    groups: list[Aggregate],
    gates: list[Gate],
    missing: list[str],
    *,
    calibrations: list[Calibration] | None = None,
    reliabilities: list[SourceReliability] | None = None,
    environments: dict[str, dict] | None = None,
    fidelity: dict[str, dict] | None = None,
) -> str:
    return json.dumps(
        {
            "dataset": dataset["version"],
            "gatePassed": all(result.passed for result in gates),
            "gateReasons": [reason for result in gates for reason in result.reasons],
            "groups": [asdict(group) for group in groups],
            "scores": [asdict(score) for score in scores],
            "missingRuns": missing,
            "calibration": [asdict(item) for item in calibrations or []],
            "sourceReliability": [asdict(item) for item in reliabilities or []],
            "environments": environments or {},
            "fidelity": fidelity or {},
        },
        indent=2,
    ) + "\n"

